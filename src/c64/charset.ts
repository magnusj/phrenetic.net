const buildCharset = (): Uint8Array => {
  // 4 KB like the real character ROM; the second 2 KB half mirrors the first
  const rom = new Uint8Array(0x1000);
  for (const [code, glyph] of Object.entries(GLYPHS)) {
    const rows = glyph.trim().split('\n');
    rows.forEach((row, y) => {
      let byte = 0;
      for (let x = 0; x < 8; x++) {
        if (row[x] === '#') byte |= 0x80 >> x;
      }
      rom[Number(code) * 8 + y] = byte;
    });
  }
  for (let i = 0; i < 128 * 8; i++) {
    rom[128 * 8 + i] = ~rom[i] & 0xff;
  }
  rom.copyWithin(0x800, 0, 0x800);
  return rom;
};

export const CHAR_ROM = buildCharset();

// Convert text to C64 screen codes (upper case set). '^' maps to the up arrow, '_' to the left arrow.
export const toScreenCodes = (text: string): number[] =>
  Array.from(text.toUpperCase(), (ch) => {
    const c = ch.charCodeAt(0);
    if (c >= 0x40 && c <= 0x5a) return c - 0x40; // @, A-Z
    if (c >= 0x20 && c <= 0x3f) return c; // space, punctuation, digits
    if (ch === '[') return 27;
    if (ch === '£') return 28;
    if (ch === ']') return 29;
    if (ch === '^') return 30;
    if (ch === '_') return 31;
    return 32;
  });
